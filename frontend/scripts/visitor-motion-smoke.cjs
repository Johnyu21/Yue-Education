const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path')
const base=process.env.VISITOR_UI_URL||'http://127.0.0.1:5174',out=path.resolve('../backend/logs/frontend-ui-qa/motion')
fs.mkdirSync(out,{recursive:true})
let browser,page;const errors=[],checks=[]
const pass=name=>{checks.push(name);console.log('PASS '+name)}
(async()=>{
 browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
 const context=await browser.newContext({viewport:{width:1600,height:1000}})
 page=await context.newPage();page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base+'/#/',{waitUntil:'domcontentloaded'})
 await page.locator('.visitor-promo.is-expanded').waitFor()
 await page.getByRole('button',{name:'了解留学项目',exact:true}).waitFor()
 await page.getByRole('button',{name:'进入服务系统',exact:true}).waitFor()
 await page.waitForFunction(()=>{const v=document.querySelector('.visitor-promo-media');return v&&v.readyState>=2&&!v.paused&&v.muted&&v.loop})
 await page.waitForTimeout(900)
 await page.screenshot({path:path.join(out,'home-video-guidance.png')})
 pass('首页首访展开视频，中央引导可见，静音循环播放')
 await page.getByRole('button',{name:'了解留学项目',exact:true}).click()
 await page.waitForFunction(()=>window.scrollY>window.innerHeight*.6)
 const firstCard=page.locator('.visitor-project-card').first()
 await firstCard.scrollIntoViewIfNeeded();await page.waitForTimeout(1000)
 assert.equal(await firstCard.evaluate(e=>getComputedStyle(e).opacity),'1')
 assert.ok(await page.locator('[data-visitor-direction="left"]').count())
 assert.ok(await page.locator('[data-visitor-direction="right"]').count())
 assert.ok(await page.locator('.visitor-reading-progress').evaluate(e=>getComputedStyle(e).transform!=='matrix(0, 0, 0, 1, 0, 0)'))
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
 await page.screenshot({path:path.join(out,'scroll-projects.png')})
 pass('项目引导定位、左右滚动入场与浏览进度正常，无横向溢出')
 const gallery=page.locator('.visitor-gallery').first()
 await gallery.scrollIntoViewIfNeeded();await page.waitForTimeout(1000)
 const caption=await gallery.locator('figcaption>span').innerText()
 await gallery.getByRole('button',{name:/：下一张$/}).click()
 assert.notEqual(await gallery.locator('figcaption>span').innerText(),caption)
 await gallery.locator('.visitor-click-wave').first().waitFor({state:'attached'})
 await page.waitForTimeout(850)
 assert.equal(await gallery.locator('.visitor-click-wave').count(),0)
 pass('轮播切换和点击波纹正常，反馈元素自动清理')
 await page.locator('.public-header nav').getByRole('link',{name:'留学政策',exact:true}).click()
 await page.waitForURL('**/#/policies')
 await page.locator('.visitor-policy-card').first().scrollIntoViewIfNeeded();await page.waitForTimeout(1000)
 assert.equal(await page.locator('.visitor-policy-card').first().evaluate(e=>getComputedStyle(e).opacity),'1')
 pass('政策页面同样应用滚动动画')
 await page.locator('.public-header nav').getByRole('link',{name:'首页',exact:true}).click()
 await page.locator('.visitor-promo:not(.is-expanded)').waitFor()
 await page.getByRole('button',{name:'展开观看宣传视频',exact:true}).click()
 await page.getByRole('button',{name:'进入服务系统',exact:true}).click()
 await page.waitForURL('**/#/login')
 await page.waitForFunction(()=>{const v=document.querySelector('.login-background-video');return v&&v.readyState>=2&&!v.paused&&v.muted&&v.loop})
 const video=page.locator('.login-background-video')
 assert.match(await video.evaluate(e=>getComputedStyle(e).filter),/blur/)
 await page.getByLabel('登录账号',{exact:true}).fill('layout-check-only')
 await page.getByLabel('密码',{exact:true}).fill('no-submit')
 await page.screenshot({path:path.join(out,'login-video-background.png')})
 pass('引导进入登录页，左侧虚化静音循环视频，登录输入不受遮挡')
 await page.getByRole('button',{name:'暂停登录页背景视频'}).click()
 assert.equal(await video.evaluate(e=>e.paused),true)
 await page.getByRole('button',{name:'播放登录页背景视频'}).click()
 await page.waitForFunction(()=>!document.querySelector('.login-background-video').paused)
 pass('登录页背景视频可暂停和继续播放')
 await page.locator('.public-header nav').getByRole('link',{name:'首页',exact:true}).click()
 await page.locator('.visitor-promo:not(.is-expanded)').waitFor()
 await page.reload({waitUntil:'domcontentloaded'})
 await page.locator('.visitor-promo.is-expanded').waitFor()
 pass('站内返回首页保持收起，刷新首页重新展开')
 const reduced=await browser.newContext({viewport:{width:1600,height:1000},reducedMotion:'reduce'})
 const quiet=await reduced.newPage();quiet.on('pageerror',e=>errors.push(e.message))
 await quiet.goto(base+'/#/policies',{waitUntil:'domcontentloaded'});await quiet.locator('.visitor-policy-card').first().waitFor()
 assert.equal(await quiet.locator('.visitor-reveal').count(),0)
 await quiet.locator('.public-header').getByRole('button',{name:/系统登录/}).click()
 await quiet.locator('.login-background-video').waitFor()
 assert.equal(await quiet.locator('.login-background-video').evaluate(e=>e.paused),true)
 await reduced.close();assert.deepEqual(errors,[])
 pass('减少动态效果时内容直接显示、登录背景暂停，页面无脚本异常')
 fs.writeFileSync(path.join(out,'motion-results.json'),JSON.stringify({checks,errors},null,2))
 console.log('VISITOR_MOTION_CHECKS '+checks.length)
})().catch(async e=>{console.error(e.stack);if(page)await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});process.exitCode=1}).finally(async()=>{await browser?.close()})
